#!/usr/bin/env python3
"""NIAH (needle-in-a-haystack) recall check against the live NInfer serve.

This is the practical quality gate for approximate (sage / nvfp4) attention:
a broken long-context attention path loses the needle. The script hits the
*already-running* server (no engine restart / reconfig) and checks whether the
exact needle string is retrieved in the model's answer to a long-context
question. It reports per-run recall (e.g. 3/3) rather than a speed metric.

Stdlib only; never restarts or reconfigures the engine. Fixtures resolve
relative to the repo root (auto-detected) unless given as an absolute path.

    python3 tools/bench/run_niah_check.py --label SAGE --runs 3
    python3 tools/bench/run_niah_check.py --fixture examples/cli/messages/long_niah_64k.json \
        --needle "ORCHID=493817; COLOR=COBALT" --max-tokens 64 --label SAGE
    # multi-key matrix (target record among 32 same-form distractors), exact answer,
    # production sampling with an independent seed per run
    python3 tools/bench/run_niah_check.py --multikey --lengths 8k,32k,64k,128k \
        --exact-answer --temperature 1.5 --runs 2 --label multikey-sampled

Structured suites use fixture-local answer metadata, never sent to the server:
    python3 tools/bench/run_niah_check.py --suite multi-value --lengths 32k,128k,260k \
        --fixture-dir out/needle/prompts --output-dir out/needle/results --key local

Structured scoring requires every expected JSON value or key/value binding and
no extras; array order is immaterial. Full answers, responses, scores, and timings
are saved after every trial. API errors fail the gate with exit 2; wrong answers
return exit 1. Standard fixtures retain substring or --exact-answer scoring.
Outputs default to profiles/bench/niah-check/ (gitignored).
"""

from __future__ import annotations

import argparse
import http.client
import json
import os
import time
import urllib.error
import urllib.request
from pathlib import Path


def repo_root() -> Path:
    """Repo root = the directory containing CMakeLists.txt (walk up from here)."""
    here = Path(__file__).resolve().parent
    for candidate in (here, *here.parents[:6]):
        if (candidate / "CMakeLists.txt").is_file():
            return candidate
    return here.parents[2]


ROOT = repo_root()
DEFAULT_BASE = os.environ.get("NINFER_BASE", "http://127.0.0.1:8081")
DEFAULT_MODEL = "coding"
DEFAULT_NEEDLE = "ORCHID=493817; COLOR=COBALT"
# Default = the light mid-spine gate (fast). The full NIAH position matrix
# (lengths x positions, generated by tools/bench/make_niah_positions.py) runs via
# --lengths + --positions (and --multikey for the distractor variant); 260k is the
# long end (the whole master stream, ~2k tokens under the 262,144 context).
DEFAULT_FIXTURES = [
    ("context_8k", "examples/cli/messages/long_niah_8k.json"),
    ("context_64k", "examples/cli/messages/long_niah_64k.json"),
]
# Position-matrix coordinates (lengths x positions). Each cell is a committed
# fixture from the generator: the mid cell uses the bare name, the other
# positions use the suffixed name (long_niah_{len}_{pos}.json).
NIAH_LENGTHS = ("8k", "32k", "64k", "100k", "128k", "150k", "200k", "240k", "260k")
# Multi-key fixtures are generated for this subset (make_niah_positions.py --multikey).
NIAH_MULTIKEY_LENGTHS = ("8k", "32k", "64k", "128k", "240k", "260k")
NIAH_POSITIONS = ("start", "q25", "mid", "q75", "end")


HARD_SUITES = (
    "multi-value",
    "multi-query",
    "variable-tracking-1x3",
    "variable-tracking-1x6",
    "variable-tracking-2x6",
    "variable-tracking",
    "aggregation",
    "in-distribution",
)


def matrix_cases(lengths, positions, multikey=False, suite="standard", fixture_dir=None):
    """Expand (lengths, positions) into (label, fixture-ref) NIAH matrix cells.

    The mid cell uses the bare fixture name (long_niah_{len}.json); every other
    position uses the suffixed name (long_niah_{len}_{pos}.json). Multi-key cells
    are always suffixed (long_niah_multikey_{len}_{pos}.json)."""
    out = []
    for length in lengths:
        for pos in positions:
            if suite != "standard":
                ref = (
                    f"examples/cli/messages/long_niah_{suite.replace('-', '_')}_{length}_{pos}.json"
                )
                label = f"{suite}_{length}_{pos}"
            elif multikey:
                ref = f"examples/cli/messages/long_niah_multikey_{length}_{pos}.json"
                label = f"multikey_{length}_{pos}"
            elif pos == "mid":
                ref = f"examples/cli/messages/long_niah_{length}.json"
                label = f"context_{length}"
            else:
                ref = f"examples/cli/messages/long_niah_{length}_{pos}.json"
                label = f"context_{length}_{pos}"
            if fixture_dir is not None:
                ref = str(Path(fixture_dir) / Path(ref).name)
            out.append((label, ref))
    return out


def load_key(api_key: str | None) -> str:
    """Use the command-line key or the NInfer key environment variable."""
    return api_key if api_key is not None else os.environ.get("NINFER_API_KEY", "")


def resolve_fixture(ref: str) -> Path:
    p = Path(ref)
    if p.is_absolute():
        return p
    for base in (ROOT, ROOT / "tools" / "bench" / "fixtures"):
        candidate = base / p
        if candidate.is_file():
            return candidate
    return p


def _unique_json_object(pairs: list[tuple]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def score_answer(text: str, expected: list[str] | dict[str, str], scoring: str) -> dict:
    """Require every expected value/binding, no extras, and an unambiguous raw JSON answer.

    Sets are order-independent but duplicates, non-string values, prose, and
    Markdown wrappers fail. Object scores preserve key/value bindings. Partial
    match counts are diagnostics only; the battery gate requires the full answer.
    """
    if scoring not in ("json-set", "json-object"):
        raise ValueError(f"unknown structured scoring: {scoring}")
    if scoring == "json-set":
        if (
            not isinstance(expected, list)
            or not expected
            or any(not isinstance(x, str) for x in expected)
            or len(set(expected)) != len(expected)
        ):
            raise ValueError("json-set metadata must contain distinct expected strings")
    elif (
        not isinstance(expected, dict)
        or not expected
        or any(not isinstance(k, str) or not isinstance(v, str) for k, v in expected.items())
    ):
        raise ValueError("json-object metadata must contain expected string bindings")
    result = {
        "passed": False,
        "matched": 0,
        "expected_count": len(expected),
        "unexpected": 0,
        "error": None,
    }
    try:
        answer = json.loads(text, object_pairs_hook=_unique_json_object)
    except (ValueError, TypeError) as exc:
        result["error"] = str(exc)
        return result
    if scoring == "json-set":
        if not isinstance(answer, list) or any(not isinstance(x, str) for x in answer):
            result["error"] = "answer must be an array of strings"
            return result
        values, targets = set(answer), set(expected)
        result["matched"] = len(values & targets)
        result["unexpected"] = len(values - targets)
        result["passed"] = values == targets and len(answer) == len(values)
        if len(answer) != len(values):
            result["error"] = "answer contains duplicate values"
    else:
        if not isinstance(answer, dict) or any(not isinstance(x, str) for x in answer.values()):
            result["error"] = "answer must be an object with string values"
            return result
        result["matched"] = sum(answer.get(key) == value for key, value in expected.items())
        result["unexpected"] = len(set(answer) - set(expected))
        result["passed"] = answer == expected
    return result


def post(base: str, key: str, body: dict, timeout: float) -> dict:
    req = urllib.request.Request(
        f"{base.rstrip('/')}/v1/chat/completions",
        data=json.dumps(body).encode(),
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode())


def content_of(data: dict) -> str:
    parts = []
    for choice in data.get("choices") or []:
        msg = choice.get("message") or {}
        if msg.get("content"):
            parts.append(msg["content"])
        if msg.get("reasoning_content"):
            parts.append(msg["reasoning_content"])
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default=DEFAULT_BASE)
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--key", default=None, help="API key (else read from env/.env)")
    ap.add_argument(
        "--needle",
        default=DEFAULT_NEEDLE,
        help="substring that must appear in the answer for a PASS",
    )
    ap.add_argument(
        "--exact-answer",
        action="store_true",
        help="require the stripped answer to equal --needle exactly",
    )
    ap.add_argument(
        "--fixture",
        action="append",
        default=None,
        help="fixture ref (repeatable). Default: 8k + 64k NIAH.",
    )
    ap.add_argument(
        "--lengths", default="", help="NIAH matrix lengths (comma list, e.g. '8k,64k,200k')"
    )
    ap.add_argument(
        "--positions",
        default="",
        help="NIAH matrix positions (comma list from "
        "start/q25/mid/q75/end, or a subset); with --lengths, "
        "runs the position-matrix cells",
    )
    ap.add_argument(
        "--multikey",
        action="store_true",
        help="run the multi-key matrix cells (32 same-form distractor records)",
    )
    ap.add_argument("--suite", choices=("standard", *HARD_SUITES), default="standard")
    ap.add_argument(
        "--fixture-dir", type=Path, help="directory containing generated matrix fixtures"
    )
    ap.add_argument("--output-dir", type=Path, default=ROOT / "profiles" / "bench" / "niah-check")
    ap.add_argument("--max-tokens", type=int, default=64)
    ap.add_argument(
        "--thinking",
        action="store_true",
        default=False,
        help="enable thinking (off by default so the answer is the needle)",
    )
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument(
        "--temperature",
        type=float,
        default=0.0,
        help="request temperature; above zero, run i uses seed + i (seed "
        "defaults to 1) so repeated runs are independent samples",
    )
    ap.add_argument("--runs", type=int, default=1, help="repeat each case N times")
    ap.add_argument("--timeout", type=float, default=600.0)
    ap.add_argument("--label", default="niah")
    args = ap.parse_args()

    if args.multikey and args.suite != "standard":
        ap.error("--multikey applies only to --suite standard")
    if args.runs < 1:
        ap.error("--runs must be positive")
    key = load_key(args.key)
    if not key:
        print(
            "ERROR: no API key (pass --key or set NINFER_API_KEY / LLAMA_CPP_LOCAL_API_KEY)",
            file=__import__("sys").stderr,
        )
        return 2

    cases = []
    if args.fixture:
        for ref in args.fixture:
            label = Path(ref).stem
            cases.append((label, ref))
    elif args.lengths or args.positions or args.multikey or args.suite != "standard":
        known_lengths = NIAH_MULTIKEY_LENGTHS if args.multikey else NIAH_LENGTHS
        lengths = (
            [p.strip() for p in args.lengths.split(",") if p.strip()]
            if args.lengths
            else list(known_lengths)
        )
        positions = (
            [p.strip() for p in args.positions.split(",") if p.strip()]
            if args.positions
            else list(NIAH_POSITIONS)
        )
        # validate against the known sets so a typo fails fast
        for length in lengths:
            if length not in known_lengths:
                raise SystemExit(
                    f"unknown NIAH length {length!r} (choose from {', '.join(known_lengths)})"
                )
        for p in positions:
            if p not in NIAH_POSITIONS:
                raise SystemExit(
                    f"unknown NIAH position {p!r} (choose from {', '.join(NIAH_POSITIONS)})"
                )
        cases = matrix_cases(lengths, positions, args.multikey, args.suite, args.fixture_dir)
    else:
        cases = DEFAULT_FIXTURES

    out_dir = args.output_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    record = {
        "label": args.label,
        "base": args.base,
        "model": args.model,
        "suite": args.suite,
        "needle": args.needle,
        "exact_answer": args.exact_answer,
        "thinking": args.thinking,
        "temperature": args.temperature,
        "seed": args.seed,
        "runs": args.runs,
        "ts": int(time.time()),
        "cases": [],
    }

    rec_path = out_dir / f"niah-check-{args.label}-{record['ts']}.json"
    if rec_path.exists():
        raise SystemExit(f"refusing to replace {rec_path}")
    all_pass = True
    errors = 0
    for label, ref in cases:
        raw = json.loads(resolve_fixture(ref).read_text(encoding="utf-8"))
        messages = raw if isinstance(raw, list) else raw["messages"]
        metadata = raw.get("niah") if isinstance(raw, dict) else None
        if metadata:
            # Validate the external answer contract before making an inference request.
            score_answer("null", metadata["expected"], metadata["scoring"])
        elif args.suite != "standard":
            raise ValueError(f"hard-suite fixture lacks answer metadata: {ref}")
        n_prompt_chars = sum(len(m.get("content", "")) for m in messages)
        retrieved = 0
        total = 0
        snippets = []
        trials = []
        case_record = {
            "label": label,
            "fixture": str(ref),
            "prompt_chars": n_prompt_chars,
            "answer_contract": metadata,
            "retrieved": 0,
            "total": 0,
            "recall": 0.0,
            "passed": False,
            "snippets": snippets,
            "trials": trials,
        }
        record["cases"].append(case_record)
        for run in range(args.runs):
            body = {
                "model": args.model,
                "messages": [dict(m) for m in messages],
                "max_tokens": args.max_tokens,
                "temperature": args.temperature,
                "chat_template_kwargs": {"enable_thinking": args.thinking},
                "enable_thinking": args.thinking,
            }
            if args.temperature > 0.0:
                body["seed"] = (args.seed if args.seed is not None else 1) + run
            elif args.seed is not None:
                body["seed"] = args.seed
            t0 = time.perf_counter()
            try:
                data = post(args.base, key, body, args.timeout)
            except (OSError, http.client.HTTPException, json.JSONDecodeError) as exc:
                total += 1
                errors += 1
                all_pass = False
                error = f"{type(exc).__name__}: {exc}"
                if isinstance(exc, urllib.error.HTTPError):
                    with exc:
                        error += ": " + exc.read().decode(errors="replace")
                snippets.append(f"RUN ERROR: {error}")
                trials.append({"run": run + 1, "passed": False, "error": error})
                case_record.update(
                    retrieved=retrieved, total=total, recall=retrieved / total, passed=False
                )
                rec_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
                print(f"  [{label}] run {run + 1}/{args.runs}: ERROR {error}")
                continue
            wall = time.perf_counter() - t0
            text = content_of(data)
            total += 1
            score = (
                score_answer(text, metadata["expected"], metadata["scoring"]) if metadata else None
            )
            ok = (
                score["passed"]
                if score
                else ((text.strip() == args.needle) if args.exact_answer else (args.needle in text))
            )
            retrieved += 1 if ok else 0
            trials.append(
                {
                    "run": run + 1,
                    "seed": body.get("seed"),
                    "passed": ok,
                    "answer": text,
                    "score": score,
                    "wall_seconds": wall,
                    "response": data,
                }
            )
            status = "PASS" if ok else "FAIL"
            all_pass = all_pass and ok
            preview = text.strip().replace("\n", " ")
            if len(preview) > 240:
                preview = preview[:240] + "..."
            seed_tag = f" (seed {body['seed']})" if "seed" in body else ""
            snippets.append(f"{status}{seed_tag}: {preview}")
            case_record.update(
                retrieved=retrieved,
                total=total,
                recall=retrieved / total,
                passed=retrieved == total,
            )
            rec_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
            print(
                f"  [{label}] run {run + 1}/{args.runs}: {status} "
                f"(wall {wall:.1f}s, needle={ok})\n      {preview}"
            )
    record["errors"] = errors
    rec_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    print(f"\nrecord -> {rec_path}")
    failed_cases = [c for c in record["cases"] if not c["passed"]]
    failed_runs = sum(c["total"] - c["retrieved"] for c in record["cases"])
    total_runs = sum(c["total"] for c in record["cases"])
    for c in failed_cases:
        nfail = c["total"] - c["retrieved"]
        print(f"  [FAIL] {c['label']}: {nfail}/{c['total']} runs failed to retrieve the needle")
    verdict = "PASS" if all_pass else "FAIL"
    print(
        f"NIAH gate: {verdict} "
        f"({len(failed_cases)}/{len(record['cases'])} cases, "
        f"{failed_runs}/{total_runs} runs failed; "
        f"all cases must retrieve the needle in every run)"
    )
    return 2 if errors else (0 if all_pass else 1)


if __name__ == "__main__":
    raise SystemExit(main())
